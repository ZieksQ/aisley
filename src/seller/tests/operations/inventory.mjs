import assert from 'node:assert/strict'
import { captureResponsive, pressKey } from './support.mjs'

const api = '/api/v1/seller/inventory'
const ids = {
  active: '21000000-0000-4000-8000-000000000001',
  low: '21000000-0000-4000-8000-000000000002',
  out: '21000000-0000-4000-8000-000000000003',
  archived: '21000000-0000-4000-8000-000000000004',
}

export async function reviewInventory(browser) {
  await browser.cdp('Emulation.setTimezoneOverride', { timezoneId: 'Asia/Manila' })
  await browser.setNextModes({ inventoryList: 'loading' })
  await browser.navigate('/inventory')
  await browser.waitForStatus('Loading inventory…')
  assert.equal(await browser.evaluate("return [...document.querySelectorAll('button')].find(item => item.getAttribute('aria-label') === 'Refresh inventory')?.disabled"), true, 'Refresh is disabled while the inventory snapshot is loading')
  await browser.waitText('Cedar Storage Basket')
  await browser.waitForRequest((item) => item.path === api && item.method === 'GET', 'initial inventory snapshot')
  const table = await browser.evaluate("return Boolean(document.querySelector('[role=region][aria-label=\"Shop inventory\"]'))")
  assert.ok(table, 'Inventory is exposed as a named, keyboard-focusable table region')
  assert.equal(await browser.evaluate("return document.querySelector('[role=region][aria-label=\"Shop inventory\"]')?.getAttribute('tabindex')"), '0')
  const firstRow = await browser.evaluate("return [...document.querySelectorAll('tbody tr')].find(row => row.innerText.includes('Cedar Storage Basket'))?.innerText ?? ''")
  assert.match(firstRow, /11[\s\S]*2[\s\S]*9/, 'Inventory rows show on-hand, reserved and available values from the same snapshot')
  await browser.viewport(320, 760, false)
  const scrollRegion = await browser.evaluate("return (() => { const region = document.querySelector('[role=region][aria-label=\"Shop inventory\"]'); return region && { client: region.clientWidth, content: region.scrollWidth, overflow: getComputedStyle(region).overflowX } })()")
  assert.ok(scrollRegion && scrollRegion.content > scrollRegion.client, `Wide inventory columns remain in their own scroll region at 320px: ${JSON.stringify(scrollRegion)}`)
  await browser.assertNoHorizontalOverflow('Inventory table at 320px')

  // The slower first result must not replace a later search result.
  await browser.setMode('inventoryList', 'delay-search')
  await browser.setField('Search product or SKU', 'Cedar')
  await browser.clickText('Search')
  await browser.waitForRequest((item) => item.path === api && new URLSearchParams(item.query).get('search') === 'Cedar', 'slow earlier inventory search')
  await browser.setField('Search product or SKU', 'Olive')
  await browser.clickText('Search')
  await browser.waitText('Olive Oil Set')
  await new Promise((done) => setTimeout(done, 750))
  await browser.until("return !document.querySelector('tbody')?.innerText.includes('Cedar Storage Basket')", 'stale inventory response does not replace the newest search')
  const searches = (await browser.requests()).filter((item) => item.path === api && item.method === 'GET')
  assert.ok(searches.some((item) => new URLSearchParams(item.query).get('search') === 'Olive'))
  assert.equal(await browser.evaluate("return document.querySelector('tbody')?.innerText.includes('Cedar Storage Basket') ?? false"), false, 'Only the current search result is rendered after an out-of-order response')

  await browser.setField('Stock state', 'low')
  await browser.waitText('Olive Oil Set')
  await browser.until("return new URLSearchParams(window.operationsFixture.requests.filter(item => item.path === '/api/v1/seller/inventory').at(-1)?.query ?? '').get('stock') === 'low'", 'stock filter request')
  await browser.setField('Stock state', '')
  await browser.setField('Search product or SKU', '')
  await browser.clickText('Search')
  await browser.waitText('Cedar Storage Basket')
  await browser.clickText('Next')
  await browser.waitText('Blue Glaze Mug')
  await browser.waitText('Linen Gift Set')
  assert.match(await browser.evaluate("return document.querySelector('[role=region][aria-label=\"Shop inventory\"]')?.innerText ?? ''"), /Archived product/)
  await browser.clickText('Previous')
  await browser.waitText('Cedar Storage Basket')

  await browser.setMode('inventoryList', 'empty')
  await browser.clickName('Refresh inventory')
  await browser.waitText('No inventory matches this view')
  await browser.setMode('inventoryList', 'error')
  await browser.clickName('Refresh inventory')
  await browser.waitText('Inventory service is unavailable.')
  await browser.setMode('inventoryList', 'normal')
  await browser.clickText('Try again')
  await browser.waitText('Cedar Storage Basket')

  // Detail carries authoritative stock, immutable movement deltas, and the
  // exact retry identity for a mutation whose server response was uncertain.
  await browser.navigate(`/inventory/${ids.active}`)
  await browser.waitText('Movement history')
  await browser.waitText('First-mile pickup confirmed')
  await browser.waitForRequest((item) => item.path === `${api}/${ids.active}/movements`, 'inventory movement history')
  const jumpLinks = await browser.evaluate("return ['adjust-stock', 'stock-threshold'].map(id => { const link = document.querySelector(`a[href='#${id}']`); const rect = link?.getBoundingClientRect(); return { id, width: rect?.width ?? 0, height: rect?.height ?? 0 } })")
  assert.ok(jumpLinks.every((link) => link.width >= 44 && link.height >= 44), `Inventory section links meet the 44px target: ${JSON.stringify(jumpLinks)}`)
  for (const [label, id] of [['Adjust stock', 'adjust-stock'], ['Alert threshold', 'stock-threshold']]) {
    await browser.clickText(label)
    await browser.until(`return location.hash === '#${id}'`, `${label} section link updates the fragment`)
    await browser.until(`(() => { const section = document.getElementById('${id}'); const toolbar = document.querySelector('.portal-toolbar'); return section && toolbar && section.getBoundingClientRect().top >= toolbar.getBoundingClientRect().bottom - 1 && section.getBoundingClientRect().top < innerHeight })()`, `${label} section is visible below the sticky toolbar`)
  }
  await browser.assertNoHorizontalOverflow('Inventory detail at 320px')
  const fulfillmentRow = await browser.evaluate("return [...document.querySelectorAll('[aria-label=\"Inventory movement history\"] tbody tr')].find(row => row.innerText.includes('First-mile pickup confirmed'))?.innerText ?? ''")
  assert.match(fulfillmentRow, /-2[\s\S]*-2[\s\S]*11 on hand[\s\S]*2 reserved/, `Fulfillment history shows both authoritative deltas and resulting balances: ${fulfillmentRow}`)
  const reservationRow = await browser.evaluate("return [...document.querySelectorAll('[aria-label=\"Inventory movement history\"] tbody tr')].find(row => row.innerText.includes('Order placed'))?.innerText ?? ''")
  assert.match(reservationRow, /\+4/, `Reservation movements show their reserved delta: ${reservationRow}`)
  assert.match(await browser.evaluate("return document.body.innerText"), /Asia\/Manila/)

  await browser.setMode('adjustment', 'validation')
  await browser.setField('Adjustment type', 'manual_increase')
  await browser.setField('Quantity', '2')
  await browser.setField('Reason', 'Cycle count, front shelf')
  await browser.clickText('Record adjustment')
  await browser.waitText('Review this adjustment.')
  assert.equal(await browser.evaluate("return document.querySelector('#adjustment-reason')?.value"), 'Cycle count, front shelf', 'Validation feedback preserves the Seller’s reason')
  assert.equal(await browser.evaluate("return document.querySelector('#adjustment-quantity')?.value"), '2', 'Validation feedback preserves the requested quantity')
  await browser.setMode('adjustment', 'uncertain-once')
  await browser.clickText('Record adjustment')
  await browser.waitText('Retry the exact saved request')
  const initialWrites = await browser.evaluate(`return window.operationsFixture.writes.filter(item => item.path === '${api}/${ids.active}/adjustments')`)
  assert.equal(initialWrites.length, 2, 'One validation response and one uncertain adjustment have been sent')
  const uncertain = initialWrites.at(-1)
  assert.deepEqual({ movement_type: uncertain.body.movement_type, quantity: uncertain.body.quantity, reason: uncertain.body.reason }, {
    movement_type: 'manual_increase', quantity: 2, reason: 'Cycle count, front shelf',
  })
  assert.ok(uncertain.body.idempotency_key, 'Adjustment has a stable idempotency identity')
  assert.equal(await browser.evaluate("return document.querySelector('#adjustment-quantity')?.matches(':disabled')"), true, 'Pending uncertainty locks edits to the request')
  await browser.clickText('Retry same request')
  await browser.waitText('Stock adjustment recorded.')
  const writes = await browser.evaluate(`return window.operationsFixture.writes.filter(item => item.path === '${api}/${ids.active}/adjustments')`)
  assert.equal(writes.length, 3, 'Retry resolves the first adjustment rather than recording a second one')
  assert.deepEqual(writes[1].body, writes[2].body, 'The exact serialized adjustment request is retried')
  assert.equal(await browser.evaluate('return Object.keys(window.operationsFixture.receipts).filter(key => key.startsWith("inventory:")).length'), 1, 'The backend fixture records one adjustment receipt')
  await browser.waitText('13')
  assert.equal(await browser.evaluate("return document.querySelector('[role=status]')?.innerText"), 'Stock adjustment recorded.')

  const movementRequestCount = await browser.evaluate(`return window.operationsFixture.writes.filter(item => item.path.endsWith('/adjustments')).length`)
  await browser.setField('Alert threshold', '8')
  await browser.clickText('Save threshold')
  await browser.waitText('Threshold saved.')
  const thresholdWrite = await browser.evaluate(`return window.operationsFixture.writes.findLast(item => item.path === '${api}/${ids.active}/threshold')`)
  assert.equal(thresholdWrite.method, 'PATCH')
  assert.deepEqual(thresholdWrite.body, { alert_threshold: 8 }, 'Threshold save updates only the configured threshold')
  assert.equal(await browser.evaluate(`return window.operationsFixture.writes.filter(item => item.path.endsWith('/adjustments')).length`), movementRequestCount, 'Saving a threshold does not create stock movement')
  assert.doesNotMatch(await browser.evaluate("return document.querySelector('[role=status]')?.innerText ?? ''"), /evaluat|alert created/i, 'UI does not claim immediate alert evaluation')

  // Archived catalog history is readable, but stock mutation is unavailable.
  await browser.navigate(`/inventory/${ids.archived}`)
  await browser.waitText('Archived product')
  await browser.waitText('Archived catalog history')
  assert.equal(await browser.evaluate(`return document.querySelectorAll('a[href="#adjust-stock"]').length`), 0, 'Archived/inactive stock hides the unavailable adjustment jump')
  assert.ok(await browser.evaluate(`return Boolean(document.querySelector('a[href="#stock-threshold"]'))`), 'Archived/inactive stock keeps its threshold action available')
  assert.equal(await browser.evaluate("return document.querySelector('button[type=submit]')?.innerText.trim()"), 'Record adjustment')
  assert.equal(await browser.evaluate("return document.querySelector('button[type=submit]')?.disabled"), true, 'Archived inventory remains read-only')
  assert.equal(await browser.evaluate("return document.querySelector('#stock-threshold-value')?.disabled"), false, 'A catalog archive does not prevent updating the inventory alert threshold')
  assert.deepEqual(await browser.evaluate(`return window.operationsFixture.writes.filter(item => item.path.startsWith('${api}/'))`), [], 'Archived inventory triggers no stock mutation')

  await browser.setNextModes({ inventoryDetail: 'error' })
  await browser.navigate(`/inventory/${ids.low}`)
  await browser.waitText('Inventory item could not be loaded.')
  await browser.setMode('inventoryDetail', 'normal')
  await browser.clickText('Try again')
  await browser.waitText('Olive Oil Set')
  assert.deepEqual(await browser.evaluate('return window.operationsFixture.unhandled'), [], 'All inventory browser traffic stays in the synthetic API fixture')

  await captureResponsive(browser, { route: '/inventory', expected: 'Cedar Storage Basket', prefix: 'inventory-list' })
  await captureResponsive(browser, { route: `/inventory/${ids.active}`, expected: 'First-mile pickup confirmed', prefix: 'inventory-detail' })
  await browser.navigate(`/inventory/${ids.archived}`)
  await browser.waitText('Archived catalog history')
  await browser.screenshot('inventory-archived-read-only-390-light.png')

  await browser.viewport(1440, 960, false)
  await browser.navigate(`/inventory/${ids.active}`)
  await browser.waitText('Cedar Storage Basket')
  await browser.setField('Quantity', '3')
  await browser.setField('Reason', 'Unsaved navigation guard check')
  await browser.clickText('Inventory', 'document.querySelector("main")')
  await browser.waitText('Discard unsaved inventory input?')
  assert.equal(await browser.evaluate("return document.querySelector('dialog')?.open === true"), true, 'Leaving dirty stock input opens the discard confirmation')
  await pressKey(browser, 'Escape')
  await browser.until("return !document.querySelector('dialog')", 'Escape cancels inventory discard')
  assert.equal(await browser.evaluate(`return document.querySelector('#adjustment-reason')?.value`), 'Unsaved navigation guard check', 'Canceling the guard preserves the stock reason')
  assert.equal(await browser.evaluate(`return document.querySelector('#adjustment-quantity')?.value`), '3', 'Canceling the guard preserves the stock quantity')
  assert.equal(await browser.evaluate(`return location.pathname === '/inventory/${ids.active}'`), true, 'Canceling the guard keeps the Seller on the same SKU')
  await browser.clickText('Inventory', 'document.querySelector("main")')
  await browser.waitText('Discard unsaved inventory input?')
  await browser.clickText('Discard input', 'document.querySelector("dialog")')
  await browser.until("return location.pathname === '/inventory'", 'confirmed inventory discard returns to inventory')
  await browser.until("return Boolean(document.querySelector('[role=region][aria-label=\"Shop inventory\"]')) && !document.querySelector('[aria-label=\"Inventory controls\"]')", 'confirmed discard fully releases the inventory form guard')
  await browser.clickText('Cedar Storage Basket')
  await browser.waitText('Movement history')
  await browser.setField('Adjustment type', 'manual_increase')
  await browser.setField('Quantity', '1')
  await browser.setField('Reason', 'Access-loss recovery check')
  await browser.setMode('adjustment', 'forbidden')
  await browser.clickText('Record adjustment')
  await browser.until("return location.pathname === '/login'", 'a forbidden stock mutation clears Seller access')
  await browser.waitForRequest((item) => item.path.endsWith('/auth/logout') && item.method === 'POST', 'logout after access loss')
  assert.equal(await browser.evaluate("return Boolean(document.querySelector('[aria-label=\"Inventory controls\"]'))"), false, 'Access loss removes the private inventory controls')
  assert.equal(await browser.evaluate("return document.body.innerText.includes('Retry same request')"), false, 'A forbidden mutation is not left as a retryable uncertain request')
  assert.deepEqual(await browser.evaluate('return window.operationsFixture.unhandled'), [], 'Access-loss cleanup uses only fixture-backed API calls')
  return { writes, screenshots: ['inventory-list-*.png', 'inventory-detail-*.png', 'inventory-archived-read-only-390-light.png'] }
}
