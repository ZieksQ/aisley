import assert from 'node:assert/strict'

export async function verifyPickingSheet(browser) {
  const checked = () => browser.evaluate('return document.querySelectorAll("#monitoring-results tbody input:checked").length')
  const selectPage = () => browser.clickName('Select all orders on this page', 'input')
  const selectOrder = (reference) => browser.clickName(`Select order ${reference}`, 'input')
  const ready = (reference) => browser.until(`return document.querySelector("#monitoring-results tbody") && document.querySelector("section[aria-labelledby=monitoring-results-title]").getAttribute("aria-busy") === "false" ${reference ? `&& document.querySelector('#monitoring-results tbody').textContent.includes(${JSON.stringify(reference)})` : ''}`, 'order table settles')

  assert.equal(await browser.evaluate('return document.querySelectorAll("#monitoring-results input[type=checkbox]").length'), 0)
  await browser.clickName('Select orders to print')
  assert.equal(await browser.evaluate('return document.querySelectorAll("#monitoring-results input[type=checkbox]").length'), 21)
  assert.equal(await browser.evaluate('return [...document.querySelectorAll("button")].find(button => button.textContent.includes("Print (0)"))?.disabled'), true)
  await selectOrder('ASL-20261015-4100')
  assert.equal(await checked(), 1)
  assert.equal(await browser.evaluate('return document.querySelector("#monitoring-results thead input").indeterminate'), true)
  // Native keyboard interaction toggles the focused checkbox.
  await browser.evaluate('document.querySelector("#monitoring-results tbody input").focus()')
  for (const type of ['keyDown', 'keyUp']) await browser.cdp('Input.dispatchKeyEvent', { type, key: ' ', code: 'Space', windowsVirtualKeyCode: 32 })
  await browser.until('return !document.querySelector("#monitoring-results tbody input").checked', 'Space deselects order')
  await selectPage()
  await browser.waitText('20 selected')
  await browser.clickText('Next')
  await ready('ASL-20261015-4120')
  await selectPage()
  await browser.waitText('25 selected')
  await browser.clickText('Previous')
  await ready('ASL-20261015-4100')
  assert.equal(await checked(), 20)
  await selectPage()
  await browser.waitText('5 selected')
  await selectOrder('ASL-20261015-4100')
  await browser.waitText('6 selected')

  // Stub only the native viewer; the application still fetches and opens a PDF Blob.
  await browser.evaluate(`window.open = () => ({ addEventListener: () => {}, location: { set href(value) { window.orderFixture.openedPdf = value } }, close: () => {} })`)
  await browser.clickText('Print (6)')
  await browser.until('return window.orderFixture.openedPdf?.startsWith("blob:")', 'PDF opened')
  const request = await browser.evaluate('return window.orderFixture.requests.find(item => item.path.endsWith("picking-sheet.pdf"))')
  const ids = new URLSearchParams(request.query).getAll('order_ids[]')
  assert.equal(new Set(ids).size, 6)
  assert.ok(ids.includes('90000000-0000-4000-8000-000000000001'))
  assert.ok(ids.includes('90000000-0000-4000-8000-000000000025'))
  assert.equal(request.method, 'GET')

  await browser.evaluate('window.orderFixture.pdfMode = "error"')
  await browser.clickText('Print (6)')
  await browser.waitText('Picking sheet unavailable. Please try again.')
  await browser.waitText('6 selected')
  await browser.evaluate('window.orderFixture.pdfMode = "loading"')
  await browser.clickText('Print (6)')
  await browser.waitText('Preparing PDF…')
  assert.equal(await browser.evaluate('return [...document.querySelectorAll("#monitoring-results input")].every(input => input.disabled)'), true)
  await browser.waitText('Print (6)')
  assert.equal(await browser.evaluate('return document.querySelector(".order-print-error")'), null)
  await browser.evaluate('window.open = () => null')
  await browser.clickText('Print (6)')
  await browser.waitText('Allow pop-ups for this site')
  await browser.clickText('Cancel')
  assert.equal(await browser.evaluate('return document.activeElement?.getAttribute("aria-label")'), 'Select orders to print')
  assert.equal(await browser.evaluate('return document.querySelectorAll("#monitoring-results input").length'), 0)

  // Reach the 50-order limit across three pages and retain the ability to deselect.
  await browser.evaluate(`(() => {
    const fixture = window.orderFixture;
    for (let index = 25; index < 65; index++) fixture.orders.push({ ...fixture.orders[0], id: '90000000-0000-4000-8000-' + String(index + 1).padStart(12, '0'), reference: 'ASL-LIMIT-' + index });
  })()`)
  await browser.clickText('Refresh')
  await browser.waitText('65 orders')
  await ready()
  await browser.clickName('Select orders to print')
  await selectPage()
  await browser.clickText('Next')
  await ready('ASL-LIMIT-25')
  await selectPage()
  await browser.clickText('Next')
  await ready('ASL-LIMIT-40')
  assert.equal(await browser.evaluate('return document.querySelector("#monitoring-results thead input").disabled'), true)
  for (let index = 40; index < 50; index++) await selectOrder(`ASL-LIMIT-${index}`)
  await browser.waitText('50 selected')
  assert.equal(await browser.evaluate('return [...document.querySelectorAll("#monitoring-results tbody input:not(:checked)")].every(input => input.disabled)'), true)
  await selectOrder('ASL-LIMIT-40')
  await browser.waitText('49 selected')
  assert.equal(await browser.evaluate('return [...document.querySelectorAll("#monitoring-results tbody input")].every(input => !input.disabled)'), true)

  await browser.setField('Search orders', 'Cedar')
  await browser.clickText('Search')
  await ready()
  assert.equal(await browser.evaluate('return Boolean(document.querySelector(".order-print-controls"))'), false)
  await browser.clickText('Clear search')
  await ready()
  assert.equal(await browser.evaluate('return Boolean(document.querySelector(".order-print-controls"))'), false)

  for (const theme of ['light', 'dark']) {
    for (const width of [320, 390, 768, 1440]) {
      await browser.viewport(width, 960, false)
      await browser.evaluate(`localStorage.setItem('aisley-seller-theme', '${theme}')`)
      await browser.navigate('/orders/monitoring')
      await browser.waitText('ASL-20261015-4100')
      await browser.clickName('Select orders to print')
      await selectOrder('ASL-20261015-4100')
      await browser.assertNoHorizontalOverflow(`picking selection ${width}px ${theme}`)
      assert.equal(await browser.evaluate('return [...document.querySelectorAll(".order-print-checkbox")].every(label => { const rect = label.getBoundingClientRect(); return rect.width >= 44 && rect.height >= 44 })'), true)
      await browser.screenshot(`orders-picking-selection-${width}-${theme}.png`)
    }
  }
  await browser.viewport(1440, 960, false)
  await browser.navigate('/orders/monitoring')
  await browser.waitText('ASL-20261015-4100')
  console.log('Picking sheet selection, pagination, limit, PDF retry/pop-up failures, keyboard, and responsive theme checks passed.')
}
