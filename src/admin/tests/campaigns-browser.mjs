// Start the Admin Vite server first. All campaign APIs are synthetic; no notifications are sent.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { openChatBrowser } from '../../../packages/ui/tests/chat-browser-driver.mjs';
import { installCampaignsFixture } from './campaigns-fixture.mjs';

const artifacts = resolve('node_modules/.cache/campaigns');
mkdirSync(artifacts, { recursive: true });
const origin = process.env.CAMPAIGNS_ORIGIN ?? 'http://127.0.0.1:5175';
const b = await openChatBrowser();
const js = b.evaluate;
let checks = 0;
const check = (value, label) => { assert(value, label); checks++; };
const click = text => js(`(() => {const el=[...document.querySelectorAll('.campaigns-page button, dialog button')].find(el=>el.textContent.trim()===${JSON.stringify(text)});if(!el)throw Error('Missing button: '+${JSON.stringify(text)});el.focus();el.click()})()`);
const fill = (selector, value) => js(`(() => {const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(el.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));})()`);
const select = value => js(`(() => {const el=document.querySelector('.campaign-form select');el.value=${JSON.stringify(value)};el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
const submit = () => js("document.querySelector('.campaign-form').requestSubmit()");
const draftId = '10000000-0000-4000-8000-000000000001';
const route = async (path, ready) => { await b.navigate(origin + path); await b.until(ready, path); };
const saved = "document.querySelector('.campaign-section-heading')?.innerText.includes('Saved draft')";
const formReady = "Boolean(document.querySelector('.campaign-form'))";
const previewReady = "Boolean(document.querySelector('.campaign-audience-estimate'))";
async function snapshots(name) {
  for (const dark of [false, true]) for (const width of [1440, 768, 390]) {
    await b.viewport(width, 900);
    await js(`document.documentElement.classList.toggle('dark',${dark});window.scrollTo(0,0)`);
    await new Promise(done => setTimeout(done, 80));
    check(await js('document.documentElement.scrollWidth<=innerWidth'), `${name}/${dark}/${width} overflow`);
    check(await js("document.querySelectorAll('h1').length===1"), 'one heading across shell and workspace');
    await b.screenshot(resolve(artifacts, `${name}-${dark ? 'dark' : 'light'}-${width}.png`));
    // Freeze the rendered application, including Vite's actual CSS, for the Taste meter.
    const html = await js(`(() => {const root=document.documentElement.cloneNode(true);root.querySelectorAll('script').forEach(el=>el.remove());const base=document.createElement('base');base.href=${JSON.stringify(origin)};root.querySelector('head').prepend(base);return '<!doctype html>'+root.outerHTML})()`);
    writeFileSync(resolve(artifacts, `${name}-${dark ? 'dark' : 'light'}-${width}.html`), html);
  }
  await b.viewport(1440, 900);
  await js("document.documentElement.classList.remove('dark')");
}
try {
  await b.cdp('Page.addScriptToEvaluateOnNewDocument', { source: `(${installCampaignsFixture.toString()})()` });
  await route('/notification-campaigns', "document.querySelectorAll('.campaign-row').length===20");
  await snapshots('history');
  await click('Next');
  await b.until("location.search==='?page=2'&&document.querySelectorAll('.campaign-row').length===3", 'page two');
  await js('history.back()');
  await b.until("!location.search&&document.querySelectorAll('.campaign-row').length===20", 'back restores page');
  check(true, 'URL pagination and browser back');
  await js('window.campaignFixture.failList=true'); await click('Refresh');
  await b.until("document.body.innerText.includes('Could not load campaign history')", 'history failure');
  check(await js("document.querySelectorAll('.campaign-row').length===20"), 'refresh retains previous history');
  await js('window.campaignFixture.failList=false'); await click('Retry history');
  await b.until("!document.body.innerText.includes('Could not load campaign history')", 'history recovered');

  await route('/notification-campaigns/new', formReady);
  await snapshots('composer');
  await b.cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
  check(await js("matchMedia('(prefers-reduced-motion: reduce)').matches&&getComputedStyle(document.querySelector('.campaign-form button')).transitionDuration==='0s'"), 'reduced motion preserves visible controls without transitions');
  await b.cdp('Emulation.setEmulatedMedia', { features: [] });
  await b.viewport(390,900);
  await fill('.campaign-form input', 'Long title '.repeat(10));
  await fill('.campaign-form textarea', 'ContinuousWord'.repeat(140));
  check(await js('document.documentElement.scrollWidth<=innerWidth'), 'long title and unbroken message wrap on phone');
  await js("document.documentElement.style.fontSize='200%'");
  check(await js('document.documentElement.scrollWidth<=innerWidth'), 'composer at 200% text size');
  await js("document.documentElement.style.fontSize=''");
  await b.viewport(1440,900);
  await fill('.campaign-form input', 'A message <script>plain text</script>');
  await fill('.campaign-form textarea', 'Discover the November collection.\nShop thoughtful finds from local stores.');
  check(await js("document.querySelector('.campaign-message-title').textContent.includes('<script>plain text</script>')&&!document.querySelector('.campaign-preview script')"), 'live preview is plain text');
  await select('product');
  await fill('.campaign-destination-fields input', 'product-visible');
  await select('shop');
  check(await js("document.querySelector('.campaign-destination-fields input').value===''"), 'destination type resets ID');
  await fill('.campaign-destination-fields input', 'shop-visible');
  await js("document.querySelector('.campaign-back').click()");
  await b.until("Boolean(document.querySelector('dialog[open]'))", 'unsaved guard');
  await click('Cancel');
  check(await js("location.pathname.endsWith('/new')&&document.querySelector('.campaign-form input').value.includes('plain text')"), 'cancel navigation preserves draft');
  await js('window.campaignFixture.failSave=true'); await submit();
  await b.until("Boolean(document.querySelector('.campaign-form [aria-invalid=true]'))", 'validation');
  check(await js("document.querySelector('.campaign-form input').getAttribute('aria-describedby')!==null"), 'field errors associated');
  await js('window.campaignFixture.failSave=false'); await submit();
  await b.until(`location.pathname!='/notification-campaigns/new'&&${saved}`, 'created draft route');
  check(await js("window.campaignFixture.calls.filter(c=>c.method==='POST'&&c.path.endsWith('/notification-campaigns')).length===2"), 'one create per submission including rejected validation');
  await snapshots('draft');
  await click('Calculate audience'); await b.until(previewReady, 'audience');
  await fill('.campaign-form textarea', 'Updated message with saved-revision review.');
  check(await js("!document.querySelector('.campaign-audience-estimate')"), 'edits invalidate preview');
  check(await js("[...document.querySelectorAll('button')].find(el=>el.textContent==='Calculate audience').disabled"), 'unsaved changes block calculation');
  await submit(); await b.until(saved, 'save updated draft');
  check(await js("Object.keys(window.campaignFixture.calls.findLast(c=>c.method==='PATCH').body).sort().join(',')==='audience_key,body,destination_id,destination_type,revision,title'"), 'update payload retains exact API shape');
  await js('window.campaignFixture.eligible=0'); await click('Calculate audience'); await b.until(previewReady, 'zero preview');
  check(await js("document.body.innerText.includes('No Customers currently qualify.')&&![...document.querySelectorAll('button')].some(el=>el.textContent==='Review send')"), 'empty audience cannot send');
  await js('window.campaignFixture.eligible=10001'); await click('Recalculate audience');
  await b.until("document.body.innerText.includes('exceeds the send limit')", 'oversized audience');
  await js('window.campaignFixture.eligible=120;window.campaignFixture.failPreview=true'); await click('Recalculate audience');
  await b.until("document.body.innerText.includes('Audience unavailable.')", 'preview error');
  check(await js("!document.querySelector('.campaign-audience-estimate')"), 'failed recalculation clears obsolete preview');
  await js('window.campaignFixture.failPreview=false'); await click('Calculate audience'); await b.until(previewReady, 'preview retry');
  await click('Review send'); await b.until("Boolean(document.querySelector('dialog[open]'))", 'confirmation');
  check(await js("document.activeElement.textContent==='Cancel'"), 'confirmation opens on safe cancel');
  await snapshots('confirmation');
  await b.cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 });
  await b.cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 });
  check(await js("document.activeElement.textContent==='Confirm and queue'"), 'keyboard reaches send confirmation');
  await b.cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await b.until("!document.querySelector('dialog[open]')", 'Escape cancels confirmation');
  check(await js("document.activeElement.textContent==='Review send'"), 'confirmation restores focus');
  await click('Review send');
  await js('window.campaignFixture.timeout=true;window.campaignFixture.failDetail=true');
  await click('Confirm and queue');
  await b.until("document.body.innerText.includes('Send outcome unknown')", 'uncertain send');
  check(await js("document.querySelector('.campaign-form fieldset').disabled"), 'uncertain send locks edits');
  await click('Retry status check');
  await b.until("document.body.innerText.includes('Status unavailable.')", 'failed reconciliation');
  check(await js("document.querySelector('.campaign-form fieldset').disabled"), 'failed reconciliation keeps lock');
  await js('window.campaignFixture.failDetail=false'); await click('Retry status check');
  await b.until("!document.querySelector('.campaign-form fieldset').disabled", 'reconciled draft');
  await click('Calculate audience'); await b.until(previewReady, 'recalculate after uncertain outcome');
  await click('Review send'); await js('window.campaignFixture.timeout=false'); await click('Confirm and queue');
  await b.until("Boolean(document.querySelector('.campaign-results'))", 'queued results');
  check(await js("(()=>{const c=window.campaignFixture.calls.filter(c=>c.path.endsWith('/send'));return c.length===2&&c[0].key===c[1].key&&c[0].body.revision===c[1].body.revision})()"), 'uncertain retry preserves key and revision');
  await snapshots('delivery');
  await js("Object.assign(window.campaignFixture.rows[0],{status:'completed',snapshot_count:120,delivered_count:118,skipped_count:2,failed_count:0})");
  await b.until("document.querySelector('.campaign-status')?.textContent==='Completed'", 'poll reaches terminal state');
  check(await js("document.querySelector('[data-result=Persisted] dd').textContent==='118'"), 'authoritative polled counters');

  await route(`/notification-campaigns/${draftId}`, formReady);
  await fill('.campaign-form textarea', 'Retained local text after revision conflict.');
  await js('window.campaignFixture.stale=true'); await submit();
  await b.until("document.body.innerText.includes('A newer version is available')", 'stale revision');
  check(await js("document.querySelector('textarea').value==='Retained local text after revision conflict.'"), 'conflict retains draft');
  await js('window.campaignFixture.stale=false'); await submit(); await b.until(saved, 'conflict recovery');
  await click('Calculate audience'); await b.until(previewReady, 'commit timeout preview');
  await click('Review send'); await js('window.campaignFixture.commitTimeout=true'); await click('Confirm and queue');
  await b.until("Boolean(document.querySelector('.campaign-results'))", 'committed timeout reconciled');
  check(await js("!document.querySelector('.campaign-form')"), 'accepted timeout never offers resend');

  await route(`/notification-campaigns/${draftId}`, formReady);
  await fill('.campaign-form textarea', 'Private unsaved content');
  await js("window.campaignFixture.account='other-admin';window.dispatchEvent(new Event('admin:authorization-changed'))");
  await b.until("document.querySelector('textarea')?.value!=='Private unsaved content'", 'account switch disposal');
  check(true, 'account switch drops unsaved data');
  await js("window.campaignFixture.manage=false;window.dispatchEvent(new Event('admin:authorization-changed'))");
  await b.until("document.body.innerText.includes('viewing campaigns only')", 'view-only');
  check(await js("document.body.innerText.includes('viewing campaigns only')"), 'view-only saved detail');
  await js("window.campaignFixture.view=false;window.dispatchEvent(new Event('admin:authorization-changed'))");
  await b.until("document.body.innerText.includes('Access restricted')", 'access loss');
  check(await js("!document.body.innerText.includes('Private unsaved content')&&!document.querySelector('.campaign-preview')"), 'permission loss clears workspace');
  await route('/notification-campaigns/new', formReady);
  await fill('.campaign-form input', 'Late create response');
  await fill('.campaign-form textarea', 'This response must not navigate the next account.');
  await js('window.campaignFixture.delay=600'); await submit();
  await b.until("document.querySelector('.campaign-form fieldset').disabled", 'save in flight');
  await js("window.campaignFixture.account='next-account';window.dispatchEvent(new Event('admin:authorization-changed'))");
  await b.until("document.querySelector('.campaign-form input')?.value===''", 'new session composer');
  await new Promise(done=>setTimeout(done,800));
  check(await js("location.pathname.endsWith('/new')&&document.querySelector('.campaign-form input').value===''"), 'late create cannot populate or navigate another account');
  await route('/notification-campaigns', "Boolean(document.querySelector('.campaign-row'))");
  await js('window.campaignFixture.delay=600'); await click('Next'); await js('history.back()');
  await b.until("!location.search&&document.querySelectorAll('.campaign-row').length===20", 'out of order pages');
  await new Promise(done=>setTimeout(done,800));
  check(await js("document.querySelectorAll('.campaign-row').length===20"), 'late page response ignored');
  await js('window.campaignFixture.delay=0;window.campaignFixture.rows.length=0'); await click('Refresh');
  await b.until("document.body.innerText.includes('No campaigns yet')", 'empty history');
  check(await js("!document.querySelector('.portal-pagination')"), 'no pagination for empty history');
  check(b.errors.length===0, 'no runtime exceptions');
  writeFileSync(resolve(artifacts,'browser-result.json'), JSON.stringify({ checks, runtimeErrors: b.errors },null,2));
  console.log(`Campaigns: ${checks} checks passed; artifacts at ${artifacts}`);
} finally { b.close(); }
